def ts(node):
    if '$ref' in node: return node['$ref'].split('/')[-1]
    if 'enum' in node: return ' | '.join(json.dumps(v) for v in node['enum'])
    if 'const' in node: return json.dumps(node['const'])
    if 'anyOf' in node: return ' | '.join(ts(n) for n in node['anyOf'])
    kind=node.get('type')
    if kind=='null': return 'null'
    if kind=='string': return 'string'
    if kind in ('number','integer'): return 'number'
    if kind=='boolean': return 'boolean'
    if kind=='array':
        if 'prefixItems' in node: return '['+', '.join(ts(n) for n in node['prefixItems'])+']'
        return '('+ts(node.get('items',{}))+')[]'
    if kind=='object':
        props=node.get('properties')
        if props:
            return '{ '+ '; '.join(json.dumps(k)+('' if k in node.get('required',[]) else '?')+': '+ts(v) for k,v in props.items())+' }'
        additional=node.get('additionalProperties',{})
        return 'Record<string, '+(ts(additional) if isinstance(additional,dict) else 'unknown')+'>'
    return 'unknown'

def generate(modules=(contracts,)):
    schemas={}
    for name,cls in [entry for module in modules for entry in inspect.getmembers(module,inspect.isclass)]:
        if issubclass(cls,BaseModel) and cls is not BaseModel:
            schema=cls.model_json_schema(); schemas.update(schema.pop('$defs',{})); schemas[name]=schema
    return '// Generated by scripts/generate_contracts.py; do not edit.\n'+ '\n'.join('export type '+name+' = '+ts(schema)+';\n' for name,schema in sorted(schemas.items()))

